"""Credential-free, durable sales ledger for NV automation.

Jobs are execution state, not orders. Only the persisted, cycle-verified NV
sale evidence may open an order. Account deletion and task cleanup never cascade
into this ledger. Money is stored as integer CNY cents. Once the frozen warranty
deadline passes, the frozen listing price becomes the received amount unless an
operator supplied an explicit override (including zero). Mother costs remain
explicit operator entries; listing prices are never read from current settings.
Verified NV buyer refunds take precedence over both amounts without erasing
the original order or its manual financial audit trail.
"""
